// Recolour the pixels of the original raster illustration, retaining its drawn detail,
// grain and texture. No shapes, icons or new artwork are generated by code.
function recolouredArt(img,style,choice){
  if(style==='chalk'&&choice!=='microphone'&&choice!=='question-mark')return img;
  const [dark,light]=printColours(style),key=style+'|'+choice;
  if(recolouredCache.has(key))return recolouredCache.get(key);
  const [w,h]=imageDimensions(img),out=document.createElement('canvas');out.width=w;out.height=h;
  const cx=out.getContext('2d',{willReadFrequently:true});cx.drawImage(img,0,0,w,h);
  const frame=cx.getImageData(0,0,w,h),data=frame.data;
  const rgb=hex=>[1,3,5].map(n=>parseInt(hex.slice(n,n+2),16));
  const a=rgb(dark),b=rgb(light);
  const lum=(r,g,b)=>.2126*r+.7152*g+.0722*b;
  let lo=255,hi=0;
  for(let i=0;i<data.length;i+=4){const v=lum(data[i],data[i+1],data[i+2]);lo=Math.min(lo,v);hi=Math.max(hi,v)}
  const range=Math.max(1,hi-lo);
  for(let i=0;i<data.length;i+=4){const t=Math.max(0,Math.min(1,(lum(data[i],data[i+1],data[i+2])-lo)/range));for(let k=0;k<3;k++)data[i+k]=Math.round(a[k]+(b[k]-a[k])*t)}
  cx.putImageData(frame,0,0);recolouredCache.set(key,out);return out;
}
